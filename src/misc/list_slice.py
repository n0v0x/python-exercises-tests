"""
Срез — это способ взять часть списка (подсписок) по правилу «от индекса A до индекса B».
Он создаёт новый список, а исходный не меняется.

Уровень 1: сам список.
Срез создаёт новый объект списка. У него другой id().
Это не ссылка на старый список, это отдельный список.

Уровень 2: элементы внутри.
Срез копирует ссылки на элементы, а не сами элементы.
Новый список наполняется ссылками на те же объекты, что лежат в исходном.

Это называется shallow copy — поверхностная копия (или «неглубокая копия»).
Shallow copy (поверхностная): новый контейнер, но элементы — те же объекты (те же ссылки).
Deep copy (глубокая): новый контейнер и новые копии всех вложенных объектов рекурсивно.
"""

arr = [1, 2, 3, 4, 5]
print("1). Проверка id() для двух списков.")
print("Начальный список = ", *arr, ", id(arr) = ", id(arr))
print(" ")

arr_slice = arr[1:3]        # list_slice = [2, 3] — новый список
print("Сделали срез списка в новой переменной arr_slice:")
print("arr_slice = ", *arr_slice, ", id(arr_slice) = ", id(arr_slice))
print(" ")

arr_slice[0] = 999         # меняем list_slice
print("Изменили срез списка в переменной arr_slice:")
print("arr = ", *arr, ", id(arr) = ", id(arr))    # [1, 2, 3, 4, 5] — arr не изменился
print("arr_slice = ", *arr_slice, ", id(arr_slice) = ", id(arr_slice))    # [999, 3]
print(" ")
print("Результат 1: разные id() доказывают, что срез создаёт новую поверхностную копию списка, а не возвращает «вид» на исходный.")
print(" ")

print("2). Проверка id() для одного и того же элемента из двух списков.")
print("Начальный список: ", "arr[2] = ", arr[2], ", id(arr[2]) = ", id(arr[2]))
print("Срез списка: ", "arr_slice[1] = ", arr_slice[1], ", id(arr_slice[1]) = ", id(arr_slice[1]))
print(" ")
print("Результат 2: одинаковые id() для одних и тех же элементов для разных списков доказывают, что копия списка в срезе поврхностная: новый контейнер, но элементы — те же объекты (те же ссылки).")
print(" ")